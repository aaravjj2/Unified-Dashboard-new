from playwright.sync_api import sync_playwright
p = sync_playwright().start()
b = p.chromium.launch(headless=True)
page = b.new_page(viewport={"width":1920,"height":1080})
page.goto('http://localhost:8050', wait_until='networkidle')
print('content-length', len(page.content()))
print('has toggle by querySelector', page.evaluate("() => !!document.querySelector('#chatbot-toggle-btn')"))
print('has sentinel', page.evaluate("() => !!document.querySelector('#chatbot-ready-sentinel')"))
print('outerHTML toggle', page.evaluate("() => { const e=document.querySelector('#chatbot-toggle-btn'); return e ? e.outerHTML : '' }"))
b.close()
p.stop()
